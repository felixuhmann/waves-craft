#!/usr/bin/env python3
"""Generate the static-curve tables of Craft Dynamics from spec/dynamics/r1/SPEC.md (Appendix A and B).

Usage: python3 plugins/dynamics/tools/gen_tables.py   (from the repository root; needs numpy and scipy)

Writes
  plugins/dynamics/source/dsp/CurveTables.h  engine tables: Appendix A with the expansion columns (0.50 ... 0.93:1)
                                             reconstructed *unlimited* above their output limit, the output-limit
                                             law, and Appendix B
  plugins/dynamics/tests/SpecTables.h        the raw spec tables (test reference)

Method (see IMPLEMENTATION_NOTES.md, "Static curve tables"):
  1. Appendix A rows were measured with a 1 kHz sine, x_det = peak - T + 1.277 dB; rows up to +41.28 dB with
     T = -40 dB, rows from +43.28 dB with T = -80 dB, i.e. the sine peak never exceeds 0 dBFS.
  2. In the T = -80 rows the expansion columns saturate (plateau) and then fall as the output limit is reached.
     Pairs (unlimited output peak, limited output peak) from those rows give the output-limit law L(y)
     (identity for y <= 0 dBFS, ceiling ~ +2.83 dBFS).
  3. The limited T = -40 entries are mapped back through L^-1 where well conditioned (output < +2.2 dBFS);
     the remaining gap is filled by a monotone cubic through the known points and the PeakRef anchors of 10.4
     (0.50:1: f(23.71) = 19.13, f(63.71) = 24.04, f(83.71) = 24.08).
"""
import pathlib
import re

import numpy as np
from scipy.interpolate import PchipInterpolator

ROOT = pathlib.Path(__file__).resolve().parents[3]
SPEC = ROOT / "spec/dynamics/r1/SPEC.md"
OUT_ENGINE = ROOT / "plugins/dynamics/source/dsp/CurveTables.h"
OUT_TEST = ROOT / "plugins/dynamics/tests/SpecTables.h"
OFFSET = 1.277


def parse():
    a, b, mode = [], [], None
    for line in SPEC.read_text(encoding="utf-8").splitlines():
        if line.startswith("## Appendix A"):
            mode = "A"
        elif line.startswith("## Appendix B"):
            mode = "B"
        if mode and re.match(r"\| [-+]\d", line):
            vals = [float(v) for v in line.strip().strip("|").split("|")]
            (a if mode == "A" else b).append(vals)
    return np.array(a), np.array(b)


A, B = parse()
XA, FA = A[:, 0], A[:, 1:]
RPOS = [0, .1, .15, .2, .25, .3, .35, .4, .5, .6, .7, .8, .9, 1.0]
SAT_FROM = {0: 57.28, 1: 63.28, 2: 69.28, 3: 77.28}  # last unlimited T = -80 row per expansion column


def plateau(c, x):
    if c == 0:
        return float(np.interp(x, [57.28, 63.71, 83.71], [23.99, 24.04, 24.08]))
    return {1: 16.83, 2: 11.07, 3: 3.37}[c]


def peak_of(x):
    return x - OFFSET + (-40.0 if x < 42 else -80.0)


# 2. output-limit law
pts = []
for c in range(4):
    for i, x in enumerate(XA):
        if x > SAT_FROM[c]:
            p = peak_of(x)
            pts.append((p + plateau(c, x), p + FA[i, c]))
pts.sort()
ly = np.array([0.0] + [p[0] for p in pts])
lo = np.maximum.accumulate(np.array([0.0] + [p[1] for p in pts]))
grid = np.arange(0, 21.0)
Lg = np.interp(grid, ly, lo)
CEIL = 2.83


def L(y):
    return y if y <= 0 else float(np.interp(y, grid, Lg)) if y < grid[-1] else CEIL


def Linv(o):
    return o if o <= 0 else float(np.interp(o, Lg, grid))


# 3. unlimited expansion columns
U = FA.copy()
for c in range(4):
    xs, fs = [], []
    for i, x in enumerate(XA):
        p, f = peak_of(x), FA[i, c]
        y = p + f
        if x > 42:
            xs.append(x)
            fs.append(plateau(c, x) if x > SAT_FROM[c] else f)
        elif y <= 0.0:
            xs.append(x)
            fs.append(f)
        elif y < 2.2:
            xs.append(x)
            fs.append(Linv(y) - p)
    if c == 0:
        xs.append(23.71)
        fs.append(19.13)
    order = np.argsort(xs)
    interp = PchipInterpolator(np.array(xs)[order], np.array(fs)[order])
    U[:, c] = np.round(interp(XA), 2)
    for i in range(1, len(XA)):
        if 20 < XA[i] < 45 and U[i, c] < U[i - 1, c]:
            U[i, c] = U[i - 1, c]

# replay check: the engine law reproduces the printed (limited) values
for c in range(4):
    for i, x in enumerate(XA):
        p = peak_of(x)
        assert abs(L(p + U[i, c]) - p - FA[i, c]) < 0.15, (c, x)

fmt = lambda v: "%+.2f" % v
o = ["// Generated by plugins/dynamics/tools/gen_tables.py from spec/dynamics/r1 Appendix A/B - do not edit.",
     "// The expansion columns (r <= 0.20) above their output limit hold reconstructed unlimited values; every",
     "// other entry is the spec value.", "#pragma once", "", "namespace craft::dynamics::dsp::tables", "{", "",
     "inline constexpr int numCurveRows = %d;" % len(XA), "inline constexpr int numCurveCols = %d;" % len(RPOS),
     "// detector coordinate of row i: x = curveX0 + 2 * i (dB)", "inline constexpr double curveX0 = %.2f;" % XA[0],
     "inline constexpr double curvePositions[numCurveCols] = { %s };" % ", ".join("%.2f" % r for r in RPOS),
     "// f_R(x) in dB, unlimited (row = x, column = ratio position)",
     "inline constexpr double curveDb[numCurveRows][numCurveCols] = {"]
for i in range(len(XA)):
    o.append("    { %s }, // %+.2f" % (", ".join(fmt(v) for v in U[i]), XA[i]))
o += ["};", "",
      "// Expansion output limit: estimated output peak (dBFS) before -> after limiting, on a 1 dB grid from 0 dB.",
      "inline constexpr int numLimitPoints = %d;" % len(grid),
      "inline constexpr double limitOutDb[numLimitPoints] = { %s };" % ", ".join("%.3f" % v for v in Lg),
      "inline constexpr double limitCeilingDb = %.2f;" % CEIL, "",
      "// Appendix B: expander unit gain h(x) (dB) vs x = e - GateOpen",
      "inline constexpr int numExpanderPoints = %d;" % len(B),
      "inline constexpr double expanderX[numExpanderPoints] = { %s };" % ", ".join("%.2f" % v for v in B[:, 0]),
      "inline constexpr double expanderDb[numExpanderPoints] = { %s };" % ", ".join("%.2f" % v for v in B[:, 1]),
      "", "} // namespace craft::dynamics::dsp::tables"]
OUT_ENGINE.write_text("\n".join(o) + "\n", encoding="utf-8")

t = ["// Generated by plugins/dynamics/tools/gen_tables.py: the raw spec r1 tables (Appendix A and B) exactly as",
     "// printed - test reference, independent of the engine tables.", "#pragma once", "", "namespace spectables", "{",
     "", "inline constexpr int rows = %d, cols = %d;" % (len(XA), len(RPOS)),
     "inline constexpr double positions[cols] = { %s };" % ", ".join("%.2f" % r for r in RPOS),
     "inline constexpr double x[rows] = { %s };" % ", ".join("%.2f" % v for v in XA),
     "inline constexpr double f[rows][cols] = {"]
for i in range(len(XA)):
    t.append("    { %s }," % ", ".join("%.2f" % v for v in FA[i]))
t += ["};", "inline constexpr int expRows = %d;" % len(B),
      "inline constexpr double expX[expRows] = { %s };" % ", ".join("%.2f" % v for v in B[:, 0]),
      "inline constexpr double expH[expRows] = { %s };" % ", ".join("%.2f" % v for v in B[:, 1]),
      "", "} // namespace spectables"]
OUT_TEST.write_text("\n".join(t) + "\n", encoding="utf-8")
print("wrote", OUT_ENGINE, "and", OUT_TEST)
