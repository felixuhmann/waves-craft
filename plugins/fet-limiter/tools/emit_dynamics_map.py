#!/usr/bin/env python3
"""Writes source/dsp/DynamicsMap.h from the JSON printed (last line) by tools/fit_dynamics.py.

Usage (from plugins/fet-limiter): python3 tools/emit_dynamics_map.py fit.txt > source/dsp/DynamicsMap.h
"""
import json
import sys

lines = open(sys.argv[1]).read().strip().splitlines()
P = json.loads(lines[-1])


def vec(v):
    return "{ " + ", ".join(f"{x:.6g}" for x in v) + " }"


attack_a4 = [P["att_1_r4"], P["rel_4_a3"], P["att_5_r4"], P["att_7_r4"]]
release_a4 = [P[f"rel_{r}_a3"] for r in range(1, 8)]
fits = {k: P[k] for k in ("rat_8_a3_r4", "rat_8_a7_r7", "rat_20_a3_r4", "rat_20_a7_r7", "rat_All_a3_r4", "rat_All_a7_r7",
                          "revB_a1_r1", "revB_a3_r4", "revB_a7_r7")}

out = []
out.append("""// Craft FET Limiter - gain-cell parameters per Revision / Ratio / Attack / Release (spec 6). Host independent.
//
// GENERATED by tools/emit_dynamics_map.py from the output of tools/fit_dynamics.py - do not edit by hand.
//
// The parameters of dsp/Dynamics.h were fitted (least squares, tools/fit_dynamics.py) to every configuration of
// tables/timing.csv and tables/release_trajectories.csv:
//   - attack group (tauAttack, beta, tauC; depthExp is common to all) for revision A ratio 4 at Attack 1 / 3 / 5 / 7,
//   - release group (tauHCharge, tauKCharge, tau1, tau2, tau3, offset, accel) for revision A ratio 4 at Release 1 .. 7,
//   - complete sets for ratios 8 / 20 / All at (Attack 3, Release 4) and (Attack 7, Release 7), and for revision B
//     (ratio 4) at (1, 1), (3, 4), (7, 7).
// Between anchors parameters are interpolated linearly in the setting (times geometrically, i.e. linearly in log,
// as spec 6.2 asks for the attack). Other ratios / revision B are expressed as modifiers relative to revision A
// ratio 4 at the same setting (time ratios, beta / offset differences), interpolated between their anchors and held
// outside; ratio 12 (not measured) uses the mean of the ratio 8 and ratio 20 modifiers; revision B with a ratio
// other than 4 combines both modifiers (assumption D2 in IMPLEMENTATION_NOTES).
#pragma once

#include <algorithm>
#include <array>
#include <cmath>

#include "Dynamics.h"
#include "Tables.h"

namespace craft::fet_limiter::dsp
{

namespace dynmap
{
    // parameter vector: tauA, beta, tauC, tauHc, tauKc, tau1, tau2, tau3, offset, accel, depthExp
    inline constexpr int numParams = 11;
    using Vec = std::array<double, numParams>;
    inline constexpr bool isLog[numParams] = { true, false, true, true, true, true, true, true, false, false, false };
""")
out.append("    inline constexpr Vec attackA4[4] = { // Attack 1, 3, 5, 7 (attack group used)")
out += [f"        Vec {vec(v)}," for v in attack_a4]
out.append("    };")
out.append("    inline constexpr double attackAnchors[4] = { 1.0, 3.0, 5.0, 7.0 };")
out.append("    inline constexpr Vec releaseA4[7] = { // Release 1 .. 7 (release group used)")
out += [f"        Vec {vec(v)}," for v in release_a4]
out.append("    };")
for k, v in fits.items():
    name = k.replace("rat_", "fit").replace("revB_", "fitB_").replace("_a", "A").replace("_r", "R")
    out.append(f"    inline constexpr Vec {name} = {vec(v)};")
out.append("""
    inline double lerp (double a, double b, double t) noexcept { return a + (b - a) * t; }

    // revision A ratio 4 at (attack, release)
    inline Vec baseA4 (double attack, double release) noexcept
    {
        Vec v {};
        // attack group: piecewise over 1, 3, 5, 7
        const double a = std::clamp (attack, 1.0, 7.0);
        int i = std::min (2, int ((a - 1.0) / 2.0));
        const double ta = (a - attackAnchors[i]) / 2.0;
        // release group: piecewise over 1 .. 7
        const double r = std::clamp (release, 1.0, 7.0);
        int j = std::min (5, int (r - 1.0));
        const double tr = r - 1.0 - double (j);
        for (int k = 0; k < numParams; ++k)
        {
            const bool att = k < 3 || k == 10;
            const double x0 = att ? attackA4[i][size_t (k)] : releaseA4[j][size_t (k)];
            const double x1 = att ? attackA4[i + 1][size_t (k)] : releaseA4[j + 1][size_t (k)];
            const double t = att ? ta : tr;
            v[size_t (k)] = isLog[k] ? std::exp (lerp (std::log (x0), std::log (x1), t)) : lerp (x0, x1, t);
        }
        return v;
    }

    // modifier (log ratio / difference) of a fitted vector relative to the A4 base at the same settings
    inline Vec modifier (const Vec& fit, double attack, double release) noexcept
    {
        const Vec b = baseA4 (attack, release);
        Vec m {};
        for (int k = 0; k < numParams; ++k)
            m[size_t (k)] = isLog[k] ? std::log (fit[size_t (k)] / b[size_t (k)]) : fit[size_t (k)] - b[size_t (k)];
        return m;
    }

    // piecewise-linear interpolation of modifiers given at anchor settings (held outside), separately for the
    // attack group (over Attack) and the release group (over Release)
    struct Anchor
    {
        double attack, release;
        Vec mod;
    };

    template <size_t N>
    Vec interpolate (const std::array<Anchor, N>& anchors, double attack, double release) noexcept
    {
        Vec m {};
        for (int k = 0; k < numParams; ++k)
        {
            const bool att = k < 3 || k == 10;
            const double s = att ? attack : release;
            auto key = [att] (const Anchor& an) { return att ? an.attack : an.release; };
            double value;
            if (s <= key (anchors[0]))
                value = anchors[0].mod[size_t (k)];
            else if (s >= key (anchors[N - 1]))
                value = anchors[N - 1].mod[size_t (k)];
            else
            {
                size_t i = 0;
                while (i + 2 < N && s > key (anchors[i + 1]))
                    ++i;
                const double t = (s - key (anchors[i])) / (key (anchors[i + 1]) - key (anchors[i]));
                value = lerp (anchors[i].mod[size_t (k)], anchors[i + 1].mod[size_t (k)], t);
            }
            m[size_t (k)] = value;
        }
        return m;
    }

    struct Modifiers
    {
        std::array<Anchor, 2> r8, r20, all;
        std::array<Anchor, 3> revB;

        Modifiers()
        {
            r8 = { Anchor { 3.0, 4.0, modifier (fit8A3R4, 3.0, 4.0) }, Anchor { 7.0, 7.0, modifier (fit8A7R7, 7.0, 7.0) } };
            r20 = { Anchor { 3.0, 4.0, modifier (fit20A3R4, 3.0, 4.0) }, Anchor { 7.0, 7.0, modifier (fit20A7R7, 7.0, 7.0) } };
            all = { Anchor { 3.0, 4.0, modifier (fitAllA3R4, 3.0, 4.0) }, Anchor { 7.0, 7.0, modifier (fitAllA7R7, 7.0, 7.0) } };
            revB = { Anchor { 1.0, 1.0, modifier (fitBA1R1, 1.0, 1.0) }, Anchor { 3.0, 4.0, modifier (fitBA3R4, 3.0, 4.0) },
                     Anchor { 7.0, 7.0, modifier (fitBA7R7, 7.0, 7.0) } };
        }
    };

    inline const Modifiers& modifiers()
    {
        static const Modifiers m;
        return m;
    }
} // namespace dynmap

inline DynParams dynamicsFor (Revision rev, Ratio ratio, double attack, double release)
{
    using namespace dynmap;
    const auto& M = modifiers();
    Vec v = baseA4 (attack, release);
    Vec mod {};
    switch (ratio)
    {
        case Ratio::R8: mod = interpolate (M.r8, attack, release); break;
        case Ratio::R20: mod = interpolate (M.r20, attack, release); break;
        case Ratio::All: mod = interpolate (M.all, attack, release); break;
        case Ratio::R12:
        {
            const Vec a = interpolate (M.r8, attack, release), b = interpolate (M.r20, attack, release);
            for (size_t k = 0; k < size_t (numParams); ++k)
                mod[k] = 0.5 * (a[k] + b[k]);
            break;
        }
        case Ratio::R4: break;
    }
    if (rev == Revision::B)
    {
        const Vec b = interpolate (M.revB, attack, release);
        for (size_t k = 0; k < size_t (numParams); ++k)
            mod[k] += b[k];
    }
    for (size_t k = 0; k < size_t (numParams); ++k)
        v[k] = isLog[k] ? v[k] * std::exp (mod[k]) : v[k] + mod[k];

    DynParams p;
    p.tauAttackMs = v[0];
    p.beta = std::clamp (v[1], -0.6, 0.6);
    p.tauCMs = v[2];
    p.tauHChargeMs = v[3];
    p.tauKChargeMs = v[4];
    p.tau1Ms = v[5];
    p.tau2Ms = v[6];
    p.tau3Ms = v[7];
    p.releaseOffsetDb = std::max (0.0, v[8]);
    p.accel = std::max (0.0, v[9]);
    p.depthExp = v[10];
    return p;
}

} // namespace craft::fet_limiter::dsp""")
print("\n".join(out))
