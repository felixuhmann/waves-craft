#!/usr/bin/env python3
"""Generate the embedded tables of Craft Opto Compressor from spec/opto-compressor/r1/tables and the fitted model.

Usage: gen_tables.py <dynamics fit json> <filter fit json>

Writes source/dsp/OptoTables.h (engine) and tests/SpecTables.h (normative tables for the tests).
"""
import collections
import csv
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
PLUGIN = HERE.parent
TABLES = PLUGIN.parents[1] / "spec/opto-compressor/r1/tables"
dyn = json.load(open(sys.argv[1]))
fil = json.load(open(sys.argv[2]))


def rows(name):
    return list(csv.DictReader(open(TABLES / name)))


def arr(values, fmt="%.10g"):
    return ", ".join(fmt % v for v in values)


PRS = [0, 2, 3, 4, 5, 6, 7, 8, 10]
static = collections.defaultdict(dict)
for r in rows("static_gr.csv"):
    static[(r["mode"], int(r["pr"]))][int(float(r["level_dBFS_sine_peak"]))] = float(r["gain_dB"])
levels = sorted(static[("C", 0)])
assert levels == list(range(-60, 2, 2))

e = ["// Generated by plugins/opto-compressor/tools/gen_tables.py - do not edit.", "#pragma once", "",
     "namespace craft::opto::dsp::tables", "{", "",
     "// Spec r1 tables/static_gr.csv: [mode C=0, L=1][PR row][level row]. Level of row i: -60 + 2 i dBFS sine peak.",
     "inline constexpr int numPrRows = %d;" % len(PRS), "inline constexpr int numLevels = %d;" % len(levels),
     "inline constexpr double prRows[numPrRows] = { %s };" % arr(PRS),
     "inline constexpr double staticGainDb[2][numPrRows][numLevels] = {"]
for m in "CL":
    e.append("  {")
    for pr in PRS:
        e.append("    { %s }," % arr([static[(m, pr)][l] for l in levels], "%.3f"))
    e.append("  },")
e += ["};", "",
      "// Fitted release time constant (ms) of the fast state at the reduction nodes (dB).",
      "inline constexpr int numReleaseNodes = 8;",
      "inline constexpr double releaseNodeDb[numReleaseNodes] = { 0.5, 2, 5, 9, 14, 19, 24, 30 };",
      "inline constexpr double releaseTauMs[numReleaseNodes] = { %s };" % arr([dyn["t%d" % i] for i in range(8)]), ""]
for k, name in (("tau0", "attackTau0Ms"), ("F1", "attackDepthDb"), ("p1", "attackDepthExp"), ("e0", "attackErrDb"),
                ("p2", "attackErrExp"), ("kmax", "attackMaxDbPerMs"), ("Smax", "slowMaxDb"), ("F0", "slowDepthDb"),
                ("a", "slowChargeA"), ("b", "slowChargeExpDepth"), ("m", "slowChargeExpFill"), ("taus", "slowDecayMs")):
    e.append("inline constexpr double %s = %.10g;" % (name, dyn[k]))
e += ["", "// Quadrature network: log-position of each all-pass pole between 12 Hz and 0.47 fs (warped), alternating branches.",
      "inline constexpr int numQuadraturePoles = %d;" % len(fil["hilbert_x"]),
      "inline constexpr double quadraturePos[numQuadraturePoles] = { %s };" % arr(fil["hilbert_x"]), "",
      "// Colouration: bell f,Q,dB; bell f,Q,dB; HF section fz,Qz,fp,Qp.",
      "inline constexpr double colour[10] = { %s };" % arr(fil["colour"]), "",
      "// Detector weighting: low shelf f,dB; bell f,Q,dB; high-pass f; Hi Freq amounts at 0, 25, 50, 75;",
      "// then the level-dependent band narrowing: band-pass Q, maximum dB, exponent, level span dB, share of the Hi Freq boost.",
      "inline constexpr double weighting[15] = { %s };" % arr(fil["hifreq"]), "",
      "} // namespace craft::opto::dsp::tables"]
(PLUGIN / "source/dsp/OptoTables.h").write_text("\n".join(e) + "\n", encoding="utf-8")


def struct_table(name, ctype, fields, data):
    o = ["struct %s { %s };" % (ctype, " ".join("%s %s;" % (t, n) for t, n in fields)),
         "inline const std::vector<%s> %s = {" % (ctype, name)]
    for d in data:
        o.append("  { %s }," % ", ".join(d))
    o.append("};")
    return o


def q(s):
    return '"%s"' % s


t = ["// Generated by plugins/opto-compressor/tools/gen_tables.py: spec r1 normative tables, exactly as published.",
     "#pragma once", "", "#include <vector>", "", "namespace spectables", "{", ""]
t += struct_table("staticGr", "StaticRow", [("char", "mode"), ("double", "pr"), ("double", "level"), ("double", "gain")],
                  [("'%s'" % r["mode"], r["pr"], r["level_dBFS_sine_peak"], r["gain_dB"]) for r in rows("static_gr.csv")])
t += struct_table("hifreq", "HiFreqRow", [("double", "freq"), ("double", "hifreq"), ("double", "level"), ("double", "gain")],
                  [(r["freq_hz"], r["hifreq"], r["level_dBFS_sine_peak"], r["gain_dB_pr6_comp"]) for r in rows("hifreq_gain.csv")])
t += struct_table("freqResponse", "FreqRow", [("double", "freq"), ("double", "gain")],
                  [(r["freq_hz"], r["gain_dB_re_1k"]) for r in rows("freq_response.csv")])
fields = [("const char*", "setting"), ("double", "burstDb"), ("double", "burstMs"), ("double", "t"), ("double", "gr")]
t += struct_table("attack", "DynRow", fields,
                  [(q(r["setting"]), r["burst_dBFS"], r["burst_ms"], r["t_ms"], r["gr_dB"]) for r in rows("attack.csv")])
o = ["inline const std::vector<DynRow> release = {"]
o += ["  { %s }," % ", ".join((q(r["setting"]), r["burst_dBFS"], r["burst_ms"], r["t_after_ms"], r["gr_dB"])) for r in rows("release.csv")]
t += o + ["};"]
t += struct_table("releaseTimes", "TimeRow", [("const char*", "setting"), ("double", "burstDb"), ("double", "burstMs"), ("double", "end"), ("double", "t63"), ("double", "t90")],
                  [(q(r["setting"]), r["burst_dBFS"], r["burst_ms"], r["gr_end_dB"], r["t63_s"], r["t90_s"]) for r in rows("release_times.csv")])
t += struct_table("harmonics", "HarmRow", [("const char*", "setting"), ("double", "freq"), ("double", "level"), ("double", "gain"), ("double", "h2"), ("double", "h3"), ("double", "h4"), ("double", "h5")],
                  [(q(r["setting"]), r["freq_hz"], r["level_dBFS"], r["gain_dB"], r["h2_dBc"], r["h3_dBc"], r["h4_dBc"], r["h5_dBc"]) for r in rows("harmonics.csv")])
t += struct_table("noise", "NoiseRow", [("const char*", "setting"), ("double", "rms"), ("double", "hum1"), ("double", "hum2"), ("double", "hum3")],
                  [(q(r["setting"]), r["noise_rms_dBFS"], r["hum1_dBFS"], r["hum2_dBFS"], r["hum3_dBFS"]) for r in rows("noise.csv")])
t += ["", "} // namespace spectables"]
(PLUGIN / "tests/SpecTables.h").write_text("\n".join(t) + "\n", encoding="utf-8")
print("ok")
