# Writes source/dsp/DynamicsFit.inc from dyn_params_{0,3,5}.json (results of dyn_fit2.py).
import json, os
H = os.path.dirname(os.path.abspath(__file__))
V = [json.load(open(os.path.join(H, f'dyn_params_{p}.json'))) for p in (0, 3, 5)]
num = lambda x: '%.6g' % x
o = ['// Generated by tools/fit/write_inc.py - do not edit. Fitted to spec/enhancer/r1/tables/band_steps.csv.',
     'namespace fit', '{',
     'inline constexpr DynamicsShape shapes[numBands][3] = {']
for b in range(5):
    o.append('    { ' + ', '.join('{ ' + ', '.join(num(abs(x)) for x in v[:11]) + ' }' for v in V) + ' },')
o.append('};')
o.append('inline constexpr double gSilence[numBands][3] = {')
for b in range(5):
    o.append('    { ' + ', '.join(num(v[11 + b]) for v in V) + ' },')
o.append('};')
o.append('inline constexpr double ceiling[numBands][3] = {')
for b in range(5):
    o.append('    { ' + ', '.join(num(v[16 + b]) for v in V) + ' },')
o += ['};', '} // namespace fit', '']
open(os.path.join(H, '../../source/dsp/DynamicsFit.inc'), 'w').write('\n'.join(o))
