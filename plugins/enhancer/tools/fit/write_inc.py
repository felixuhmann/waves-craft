# Writes source/dsp/DynamicsFit.inc from dyn_params_band.json (result of dyn_polish.py).
import json, os
H = os.path.dirname(os.path.abspath(__file__))
V = json.load(open(os.path.join(H, 'dyn_params_band.json')))
num = lambda x: '%.6g' % x
o = ['// Generated by tools/fit/write_inc.py - do not edit. Fitted to spec/enhancer/r1/tables/band_steps.csv.',
     'namespace fit', '{', 'inline constexpr DynamicsShape shapes[numBands][3] = {']
for row in V:
    o.append('    { ' + ', '.join('{ ' + ', '.join(num(x) for x in v[:11]) + ' }' for v in row) + ' },')
o += ['};', 'inline constexpr double gSilence[numBands][3] = {']
for row in V:
    o.append('    { ' + ', '.join(num(v[11]) for v in row) + ' },')
o += ['};', 'inline constexpr double ceiling[numBands][3] = {']
for row in V:
    o.append('    { ' + ', '.join(num(v[12]) for v in row) + ' },')
o += ['};', '} // namespace fit', '']
open(os.path.join(H, '../../source/dsp/DynamicsFit.inc'), 'w').write('\n'.join(o))
