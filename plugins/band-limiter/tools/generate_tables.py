#!/usr/bin/env python3
"""Generates the embedded table headers from the normative CSVs of spec/band-limiter/r1/tables.

  source/dsp/CrossoverTable.h   linear-phase low-pass shapes (used by the DSP)
  tests/SpecTables.h            every normative table (used by the tests)

Run from anywhere: python3 plugins/band-limiter/tools/generate_tables.py
"""
import csv
import math
from pathlib import Path

here = Path(__file__).resolve().parent
plugin = here.parent
tables = plugin.parent.parent / "spec" / "band-limiter" / "r1" / "tables"


def read(name):
    with open(tables / name, newline="") as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def num(x):
    v = float(x)
    return "nan_" if math.isnan(v) else repr(v)


def crossover_header():
    head, rows = read("xo_linear_lowpass.csv")
    cols = [float(h.split("_")[1]) for h in head[1:]]
    out = [
        "// Generated by tools/generate_tables.py from spec/band-limiter/r1/tables - do not edit by hand.",
        "#pragma once",
        "",
        "namespace craft::band_limiter::dsp::xotable",
        "{",
        "",
        f"inline constexpr int numOffsets = {len(rows)};",
        f"inline constexpr int numColumns = {len(cols)};",
        "inline constexpr double firstOffset = %s, offsetStep = %s;" % (rows[0][0], repr(float(rows[1][0]) - float(rows[0][0]))),
        "inline constexpr double columnHz[numColumns] = { " + ", ".join(repr(c) for c in cols) + " };",
        "",
        "// Measured low-pass value [offset][column]; unmeasured points (nan in the CSV) are filled: below the",
        "// crossover from the 80 Hz column, above it with 0. Small negative ripple is floored at 0.",
        "inline constexpr double lowpass[numOffsets][numColumns] = {",
    ]
    for r in rows:
        off = float(r[0])
        vals = []
        for i, v in enumerate(r[1:]):
            x = float(v)
            if math.isnan(x):
                x = float(r[2]) if off < 0 else 0.0
            vals.append(max(0.0, x))
        out.append("    { " + ", ".join(repr(v) for v in vals) + " },")
    out += ["};", "", "} // namespace craft::band_limiter::dsp::xotable", ""]
    (plugin / "source" / "dsp" / "CrossoverTable.h").write_text("\n".join(out), newline="\n")


def tests_header():
    out = [
        "// Generated by tools/generate_tables.py from spec/band-limiter/r1/tables - do not edit by hand.",
        "#pragma once",
        "",
        "#include <limits>",
        "",
        "namespace spec_tables",
        "{",
        "inline constexpr double nan_ = std::numeric_limits<double>::quiet_NaN();",
        "",
    ]
    head, rows = read("xo_linear_lowpass.csv")
    out.append("inline constexpr double xoColumns[] = { " + ", ".join(h.split("_")[1] + ".0" for h in head[1:]) + " };")
    out.append("inline constexpr double xoLinear[][%d] = {" % len(head))
    out += ["    { " + ", ".join(num(x) for x in r) + " }," for r in rows]
    out += ["};", ""]

    _, rows = read("xo_lowlatency_bands.csv")
    out.append("// freq, b1..b5, group delay at 48 kHz (samples)")
    out.append("inline constexpr double xoLowLatency[][7] = {")
    out += ["    { " + ", ".join(num(x) for x in r) + " }," for r in rows]
    out += ["};", ""]

    _, rows = read("distribution_two_tone.csv")
    out.append("struct TwoTone { const char* name; const char* description; double f1, out1, f2, out2, peak; };")
    out.append("inline const TwoTone twoTone[] = {")
    for r in rows:
        desc = r[1].replace('"', "")
        out.append(f'    {{ "{r[0]}", "{desc}", {r[2]}, {num(r[3])}, {r[4]}, {num(r[5])}, {num(r[6])} }},')
    out += ["};", ""]

    _, rows = read("distribution_multitone.csv")
    out.append("struct MultiTone { const char* name; double out[5]; double peak; };")
    out.append("inline const MultiTone multiTone[] = {")
    for r in rows:
        out.append(f'    {{ "{r[0]}", {{ ' + ", ".join(num(x) for x in r[2:7]) + f" }}, {num(r[7])} }},")
    out += ["};", ""]

    _, rows = read("release_steps.csv")
    out.append("struct ReleaseStep { const char* name; double grDuring, t63, t90, t99; };")
    out.append("inline const ReleaseStep releaseSteps[] = {")
    for r in rows:
        out.append(f'    {{ "{r[0]}", {num(r[2])}, {r[3]}, {r[4]}, {r[5]} }},')
    out += ["};", ""]

    head, rows = read("release_bursts.csv")
    times = [h.split("_")[1].replace("ms", "") + ".0" for h in head[2:]]
    out.append("inline constexpr double burstTimesMs[] = { " + ", ".join(times) + " };")
    out.append("struct ReleaseBurst { const char* name; double gr[%d]; };" % len(times))
    out.append("inline const ReleaseBurst releaseBursts[] = {")
    for r in rows:
        out.append(f'    {{ "{r[0]}", {{ ' + ", ".join(num(x) for x in r[2:]) + " } },")
    out += ["};", ""]

    _, rows = read("profiles.csv")
    out.append("struct ProfileRow { int index; double raw, out100, out2k, grDuring, t63, t90, t99; };")
    out.append("inline const ProfileRow profiles[] = {")
    for r in rows:
        out.append("    { " + r[0] + ", " + ", ".join(num(x) for x in r[1:]) + " },")
    out += ["};", "", "} // namespace spec_tables", ""]
    (plugin / "tests" / "SpecTables.h").write_text("\n".join(out), newline="\n")


(plugin / "tests").mkdir(exist_ok=True)
(plugin / "source" / "dsp").mkdir(parents=True, exist_ok=True)
crossover_header()
tests_header()
