"""Emit EqTables.h from grids.json (+ HP/LP corner tables)."""
import json, sys
G = json.load(open('grids.json'))
G.update(json.load(open('grids_rate.json')))
out = sys.argv[1]
NAMES = {'LFB': 'lfBell', 'LFS': 'lfShelf', 'LMF': 'lmf', 'HMF': 'hmf', 'HFB': 'hfBell', 'HFS': 'hfShelf', 'HFB44': 'hfBell44', 'HFB96': 'hfBell96', 'HFS44': 'hfShelf44', 'HFS96': 'hfShelf96'}

def arr(name, xs, fmt='%.6g', per=8):
    s = 'inline constexpr double %s[] = {\n' % name
    for i in range(0, len(xs), per):
        s += '    ' + ', '.join(fmt % x for x in xs[i:i + per]) + ',\n'
    return s + '};\n'

hdr = '''// Craft Console E - EQ / filter parameter tables (generated by tools/fit/emit.py from spec r1 Appendix A).
// DO NOT EDIT BY HAND: regenerate with tools/fit (see IMPLEMENTATION_NOTES.md).
//
// Each EQ band is a rectilinear grid over (frequency control r, Q control r, gain label dB); every node holds
// four section parameters whose meaning depends on the band kind (see EqDesign.h):
//   bell     : ln f0, peak gain dB, ln Q, high-frequency tilt dB
//   lowShelf : ln f, shelf gain dB, ln Q, companion-bell gain dB
//   highShelf: ln fz, ln Qz, ln fp, ln Qp      (general second-order shelf)
#pragma once

namespace craft::consolee::dsp::tables
{

struct BandGrid
{
    const double* f; int nf;
    const double* q; int nq;
    const double* g; int ng;
    const double* v; // nf * nq * ng * 4, index ((i * nq + j) * ng + k) * 4 + p
};

'''
body = ''
for b, n in NAMES.items():
    d = G[b]
    flat = [x for fi in d['v'] for qj in fi for gk in qj for x in gk]
    body += arr(n + 'F', d['f'], '%.6f', 11) + arr(n + 'Q', d['q'], '%.6f', 11) + arr(n + 'G', d['g'], '%.1f', 12)
    body += arr(n + 'V', flat, '%.9g', 8)
    body += 'inline constexpr BandGrid %s { %sF, %d, %sQ, %d, %sG, %d, %sV };\n\n' % (n, n, len(d['f']), n, len(d['q']), n, len(d['g']), n)

# HP corners and LP biquads per position (r = 0.05 ... 1): lowpass.py
import lowpass
import numpy as np
from scipy.optimize import least_squares
from mb import ana_db, lp2
from data import C, CF
hp = [x[0] for x in lowpass.fit_hp()]
body += '// High-pass corner (Hz) at r = 0.05, 0.10, ... 1.0 (log-linear in between; r = 0 is Off)\n'
body += arr('hpCorner', hp, '%.1f', 10)
body += '// Low-pass at r = 0.05 ... 1.0, per sample rate: pole pair (f0 Hz, Q; impulse-invariant), numerator 1 + c1 z^-1 + c2 z^-2\n'
lp = lowpass.fit_lp()
for fs, tab in lp.items():
    n = str(fs // 1000)
    body += arr('lpF0_' + n, [x[1] for x in tab], '%.2f', 10) + arr('lpQ_' + n, [x[2] for x in tab], '%.5f', 10)
    body += arr('lpC1_' + n, [x[3] for x in tab], '%.6f', 10) + arr('lpC2_' + n, [x[4] for x in tab], '%.6f', 10)
# plain analogue two-pole for rates above 96 kHz, fitted to the 96 kHz targets
fa, qa = [], []
for r in lowpass.POS:
    f, y = lowpass.target(r, 96000)
    s_ = least_squares(lambda p: ana_db([lp2(np.exp(p[0]), p[1])], f) - y, [np.log(8000), 0.7], bounds=([np.log(500), 0.4], [np.log(60000), 1.0]))
    fa.append(float(np.exp(s_.x[0]))); qa.append(float(s_.x[1]))
body += '// Low-pass above 96 kHz: analogue two-pole fitted to the 96 kHz targets\n'
body += arr('lpF0_analogue', fa, '%.2f', 10) + arr('lpQ_analogue', qa, '%.5f', 10)
open(out, 'w').write(hdr + body + '\n} // namespace craft::consolee::dsp::tables\n')
print('wrote', out)
